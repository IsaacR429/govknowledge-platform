from enum import StrEnum


class ProcessingStatus(StrEnum):
    PENDING = "PENDING"
    PROCESSING = "PROCESSING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"


class ParsingStatus(StrEnum):
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"


class ParserFailureClass(StrEnum):
    MALFORMED_PAGE_TREE = "MALFORMED_PAGE_TREE"
    UNRESOLVED_PAGE_GEOMETRY = "UNRESOLVED_PAGE_GEOMETRY"
    CORRUPT_XREF = "CORRUPT_XREF"
    CORRUPT_STREAM = "CORRUPT_STREAM"
    TIMEOUT = "TIMEOUT"
    OOM = "OOM"
    NATIVE_CRASH = "NATIVE_CRASH"
    NORMALIZATION_FAILED = "NORMALIZATION_FAILED"
    POST_NORMALIZATION_MISMATCH = "POST_NORMALIZATION_MISMATCH"
    UNKNOWN = "UNKNOWN"
